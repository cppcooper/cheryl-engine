#!/usr/bin/env python3
"""Generate private GLFW/Gainput translations from Cheryl and pinned headers."""

import argparse
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[2]
CONTROLS = ROOT / "projects/engine/include/cheryl/core/controls/button-codes.h"
GLFW = ROOT / "extern/glfw/include/GLFW/glfw3.h"
GAINPUT = ROOT / "extern/gainput/lib/include/gainput"
OUTPUT = ROOT / "projects/modules/platform/native-glfw/src/core/controls/generated-controls.inc"

# Only semantic naming differences need human decisions. Ordinary names and
# contiguous key families come from headers, including keys missing in Gainput.
KEY_NAMES = {
    "LeftBracket": "BracketLeft", "RightBracket": "BracketRight",
    "GraveAccent": "Grave", "PrintScreen": "Print", "Pause": "Break",
    "Backspace": "BackSpace", "Enter": "Return", "KeypadDecimal": "KpDelete",
}
KEYPAD_NAMES = ("Insert", "End", "Down", "PageDown", "Left", "Begin", "Right", "Home", "Up", "PageUp")
MODIFIER_NAMES = {"Shift": "Shift", "Control": "Ctrl", "Alt": "Alt", "Super": "Super"}
PAD_NAMES = {
    "LeftTrigger": "Axis4", "RightTrigger": "Axis5", "Back": "Select", "Guide": "Home",
    "DPadLeft": "Left", "DPadRight": "Right", "DPadUp": "Up", "DPadDown": "Down",
    "LeftShoulder": "L1", "RightShoulder": "R1", "LeftTriggerButton": "L2", "RightTriggerButton": "R2",
    "LeftStick": "L3", "RightStick": "R3",
}


def enumerators(source, name):
    match = re.search(r"enum(?:\s+class)?\s+" + re.escape(name) + r"\b[^{}]*\{([^}]+)\}", source)
    if not match:
        raise ValueError(f"Cannot find enumeration {name}")
    body = re.sub(r"//[^\n]*|/\*.*?\*/", "", match[1], flags=re.S)
    return [entry.strip().split("=")[0].strip() for entry in body.split(",") if entry.strip()]


def glfw_key(name):
    if name.startswith("Digit"):
        suffix = name[5:]
    elif name.startswith("Keypad"):
        suffix = "KP_" + name[6:].upper()
    else:
        suffix = re.sub(r"([a-z])([A-Z])", r"\1_\2", name).upper()
    return "GLFW_KEY_" + suffix


def gainput_key(name):
    if name.startswith("Digit"):
        return "Key" + name[5:]
    if name.startswith("Keypad") and name[6:].isdigit():
        return "KeyKp" + KEYPAD_NAMES[int(name[6:])]
    if name.startswith(("Left", "Right")):
        side = "Left" if name.startswith("Left") else "Right"
        modifier = name[len(side):]
        if modifier in MODIFIER_NAMES:
            return "Key" + MODIFIER_NAMES[modifier] + side[0]
    return "Key" + KEY_NAMES.get(name, name.replace("Keypad", "Kp"))


def generate():
    controls = CONTROLS.read_text(encoding="utf-8")
    native_keys = set(re.findall(r"^#define\s+(GLFW_KEY_\w+)\s+", GLFW.read_text(encoding="utf-8"), re.M))
    gainput_keys = set(enumerators((GAINPUT / "GainputInputDeviceKeyboard.h").read_text(encoding="utf-8"), "Key"))
    gainput_pad = set(enumerators((GAINPUT / "GainputInputDevicePad.h").read_text(encoding="utf-8"), "PadButton"))
    lines = ["// Generated by tools/input/generate_controls.py; do not edit.",
             "// SDK consumers use the committed output and need no generator.",
             "constexpr std::array key_mappings{"]
    seen = set()
    for name in enumerators(controls, "KeyboardKey"):
        if name == "Unknown":
            continue
        native = glfw_key(name)
        if native not in native_keys or native in seen:
            raise ValueError(f"No unique GLFW mapping for KeyboardKey::{name}")
        seen.add(native)
        gainput = gainput_key(name)
        gainput = "gainput::" + gainput if gainput in gainput_keys else "gainput::InvalidDeviceButtonId"
        lines.append(f"    KeyMapping{{{native}, CE::Input::KeyboardKey::{name}, {gainput}}},")
    ignored = {"GLFW_KEY_UNKNOWN", "GLFW_KEY_LAST", "GLFW_KEY_WORLD_1", "GLFW_KEY_WORLD_2"}
    if missing := native_keys - seen - ignored:
        raise ValueError(f"GLFW keys need portable identities: {sorted(missing)}")
    lines.extend(["};", "", "constexpr std::array pad_mappings{"])
    seen_pad = set()
    for name in enumerators(controls, "GamepadControl"):
        native = "PadButton" + PAD_NAMES.get(name, name[6:] if name.startswith("Button") else name)
        if native in gainput_pad:
            seen_pad.add(native)
            lines.append(f"    PadMapping{{gainput::{native}, CE::Input::GamepadControl::{name}}},")
    ignored_pad = {"PadButtonAxisCount_", "PadButtonMax_", "PadButtonCount_"}
    if missing := gainput_pad - seen_pad - ignored_pad:
        raise ValueError(f"Gainput controls need portable identities: {sorted(missing)}")
    lines.extend(["};", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when committed translations need regeneration")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            parser.error("Control translations are stale; run python3 tools/input/generate_controls.py")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    main()
