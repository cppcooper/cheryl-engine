    inline WorldProof::CaveRecipe recipe(std::size_t choice = 0) {
        const std::array<ProcGen::Index, 2> extents{31, 19};
        auto domain = ProcGen::Domain::checked(extents);
        if (!domain)
            throw std::runtime_error("Independent fixture domain invalid");
        ProcGen::CaveConfiguration config;
        config.solid_fill = choice == 2 ? 5000 : 4300;
        config.steps = choice == 2 ? 3 : 2;
        WorldProof::CaveRecipe result{
            {*domain, {choice == 1 ? 43u : 42u, choice == 2 ? 0x63617666u : 0x63617665u, 7}, config, {4096, 1024 * 1024, 1024 * 1024}}
        };
        result.adapter.id = "terrain:generated-west";
        result.adapter.layers = {"floor", "overlay"};
        result.adapter.spawns = {{"entry", "floor", 1, 1}, {"last", "overlay", 30, 18}, {"return", "floor", 29, 17}};
        return result;
    }
    inline CE::Maps::Snapshot base(std::size_t choice = 0) {
        // Complete independent metadata + frozen occupancy, not adapter conversion.
        CE::Maps::Snapshot result{
            "terrain:generated-west",
            31,
            19,
            {{"floor", {}}, {"overlay", {}}},
            {{"entry", "floor", 1, 1}, {"last", "overlay", 30, 18}, {"return", "floor", 29, 17}}
        };
        for (auto row : occupancy.at(choice))
            for (char cell : row)
                result.layers[0].cells.emplace_back(cell == '#' ? "terrain:two" : "terrain:one");
        result.layers[1].cells.resize(31 * 19);
        return result;
    }
